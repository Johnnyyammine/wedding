#!/bin/bash
# Shrinks your photos for the website and builds photos/list.js.
#   1. Put your photos (JPG, PNG or iPhone HEIC) in the photos-original folder.
#      Name the big cover photo "hero" (e.g. hero.jpg). The rest appear in name order.
#   2. Double-click this file, or run: bash tools/prepare_photos.sh
# Uses macOS's built-in "sips" tool, so nothing to install.
set -euo pipefail
cd "$(dirname "$0")/.."

SRC=photos-original
OUT=photos
mkdir -p "$OUT"
rm -f "$OUT"/[0-9][0-9].jpg

shopt -s nullglob nocaseglob
hero=( "$SRC"/hero.* )
if (( ${#hero[@]} )); then
  sips -s format jpeg -s formatOptions 78 -Z 2000 "${hero[0]}" --out "$OUT/hero.jpg" >/dev/null
  echo "Cover photo  → $OUT/hero.jpg"
fi

list="// Generated by tools/prepare_photos.sh. The gallery shows these in order.
window.PHOTOS = ["
n=0
for f in "$SRC"/*.{jpg,jpeg,png,heic,heif,webp}; do
  base=$(basename "$f"); [[ "${base%.*}" =~ ^[Hh][Ee][Rr][Oo]$ ]] && continue
  n=$((n + 1)); name=$(printf '%02d.jpg' "$n")
  sips -s format jpeg -s formatOptions 78 -Z 1600 "$f" --out "$OUT/$name" >/dev/null
  w=$(sips -g pixelWidth "$OUT/$name" | awk '/pixelWidth/ {print $2}')
  h=$(sips -g pixelHeight "$OUT/$name" | awk '/pixelHeight/ {print $2}')
  list+="
  { file: '$name', w: $w, h: $h },"
  echo "$base  → $OUT/$name (${w}×${h})"
done
printf '%s\n];\n' "$list" > "$OUT/list.js"

echo "Done: $n gallery photos. Total size: $(du -sh "$OUT" | cut -f1)"
